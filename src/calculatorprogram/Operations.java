package calculatorprogram;


public class Operations {
    
    public double add(double x, double y){
        return x + y;
    }
    public double minus(double x, double y){
        return x - y;
    }
    public double multi(double x, double y){
        return x * y;
    }
    public double div(double x, double y){
        return x / y;
    }
    
}
